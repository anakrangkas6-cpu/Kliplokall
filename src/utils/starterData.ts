export function makeAvatarDataUrl(initials: string, fromHex: string, toHex: string): string {
  const safeInitials = initials.slice(0, 2).toUpperCase();
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="240" height="240" viewBox="0 0 240 240"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0%" stop-color="${fromHex}"/><stop offset="100%" stop-color="${toHex}"/></linearGradient></defs><rect width="240" height="240" rx="120" fill="url(#g)"/><circle cx="120" cy="88" r="36" fill="rgba(255,255,255,0.22)"/><text x="120" y="136" text-anchor="middle" dominant-baseline="middle" fill="#ffffff" font-family="system-ui, -apple-system, sans-serif" font-size="82" font-weight="800" letter-spacing="-2">${safeInitials}</text></svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

